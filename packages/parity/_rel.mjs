import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/home/box/.cache/ms-playwright/chromium-1208/chrome-linux64/chrome' });
const page = await b.newPage({ viewport: { width: 1320, height: 824 } });
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto('http://127.0.0.1:5200/index.html?fixture=1&storage=memory&harness=1&sidebar=closed&theme=light#/p/page-db'); await page.waitForFunction(() => window.__inkwellReady); await page.waitForTimeout(400);
const r = await page.evaluate(async () => { const m = await import('/src/db/model.ts'); const v = m.viewsOf(window.__ink.store.get('page-db'))[0];
  const rel = m.addProp('page-db', 'relation', { name: 'Depends on', at: { viewId: v.id, after: 'title' } }); const ru = m.addProp('page-db', 'rollup', { name: 'Dep score', at: { viewId: v.id, after: rel } });
  m.updateDb('page-db', ({ schema }) => ({ schema: { ...schema, [ru]: { ...schema[ru], rollup: { relation: rel, target: 'score', fn: 'sum' } } } }), 'cfg');
  m.setValue('row-01', rel, ['row-02', 'row-03']); m.setValue('row-04', rel, ['row-01']); return { rel, ru }; });
await page.waitForTimeout(300);
await page.click(`.ink-tv-row[data-row-id="row-02"] .ink-tv-cell[data-prop="${r.rel}"]`); await page.waitForTimeout(300);
await page.screenshot({ path: '/tmp/rel1.png' });
await page.keyboard.press('Escape'); await page.waitForTimeout(200);
await page.click(`.ink-tv-hcell[data-prop="${r.ru}"]`); await page.waitForTimeout(300);
await page.screenshot({ path: '/tmp/rel2.png' });
await b.close();
