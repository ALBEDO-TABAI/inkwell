#!/usr/bin/env python3
"""Generate packages/app/src/i18n/zh-TW.ts from zh-CN.ts (OpenCC s2twp: Traditional Chinese with Taiwan phrasing).
Only string values are converted; keys and {placeholders} stay as they are. Re-run after editing zh-CN.ts."""
import re, pathlib
from opencc import OpenCC
cc = OpenCC('s2twp')
root = pathlib.Path(__file__).resolve().parent.parent / 'packages/app/src/i18n'
src = (root / 'zh-CN.ts').read_text()
def conv(m):
    q, body = m.group(2), m.group(3)
    parts = re.split(r'(\{\w+\})', body)
    return m.group(1) + q + ''.join(p if re.fullmatch(r'\{\w+\}', p) else cc.convert(p) for p in parts) + q
out = re.sub(r"(:\s*)(['\"])((?:(?!\2)[^\\]|\\.)*)\2", conv, src)
out = out.replace('export const zhCN = {', "import type { zhCN } from './zh-CN';\n/** Generated by scripts/gen-zh-tw.py from zh-CN.ts — do not edit by hand. */\nexport const zhTW: Partial<Record<keyof typeof zhCN, string>> = {", 1).replace('} as const;', '};')
(root / 'zh-TW.ts').write_text(out)
print('wrote', root / 'zh-TW.ts')
